# ============================================================
# 第7题：数据清洗 — 处理缺失值、重复值
# ============================================================
# 真实数据总有问题：空值、重复、格式不对
# 数据清洗 = 把"脏数据"变干净，是 AI 项目里最花时间的步骤

print("\n" + "=" * 50)
print("第7题：数据清洗")
print("=" * 50)

# 模拟一份有问题的数据
df_dirty = pd.DataFrame({
    "姓名": ["张三", "李四", "王五", "张三", "赵六", None, "钱七"],
    "数学": [85, None, 78, 85, 90, 88, None],
    "语文": [88, 76, 95, 88, 82, 85, 91],
    "班级": ["A", "B", "A", "A", "C", "B", "A"]
})

print("【原始数据（有问题的）】")
print(df_dirty)

# 1. 缺失值处理
print("\n【缺失值情况】")
print(df_dirty.isnull().sum())

# 策略1：用均值填充数值列的缺失值
df_clean = df_dirty.copy()
df_clean["数学"] = df_clean["数学"].fillna(df_clean["数学"].mean())  # 数学列均值填充
print("\n【数学列均值填充后】")
print(df_clean)

# 策略2：直接删除含缺失值的行
df_dropped = df_dirty.dropna()
print("\n【删除含缺失值的行后】")
print(df_dropped)

# 2. 删除重复行
print("\n【检测重复行】")
print("重复行数：", df_dirty.duplicated().sum())
print(df_dirty[df_dirty.duplicated()])  # 显示哪些行重复

df_no_dup = df_dirty.drop_duplicates()
print("\n【删除重复行后】")
print(df_no_dup)


