# 第1题：认识 Series（系列）— 带索引的一维数组
# ============================================================
# 对比：NumPy 数组没有"名字"，Pandas Series 有"名字"（索引）

print("=" * 50)
print("第1题：Series 基础")
print("=" * 50)

# 用 Python 列表创建 Series（自动生成索引 0, 1, 2...）
s = pd.Series([85, 92, 78, 90, 88])
print("Series 内容：", s)
print("Series 索引：", s.index.tolist())
print("Series 值：  ", s.values)       # 底层是 NumPy 数组
print("数据类型：  ", s.dtype)

# 用字典创建 Series（键自动变成索引）
s_dict = pd.Series({"语文": 85, "数学": 92, "英语": 78, "物理": 90})
print("\n用字典创建 Series：")
print(s_dict)
