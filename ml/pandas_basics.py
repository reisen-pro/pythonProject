"""
Pandas 基础练习
===============
Pandas = Panel Data（面板数据），是 AI 数据分析领域最常用的库。

核心数据结构：
- Series：    一列数据，像加强版的 NumPy 数组（有索引）
- DataFrame： 多列数据，像 Excel 表格（行列都有索引）

NumPy 解决"怎么算"，Pandas 解决"怎么分析数据"。

在学习之前，先思考一个问题：
当你拿到一份 Excel 表格（1000行、20列）时，你会怎么分析？
→ Pandas 就是让这个过程代码化的工具。
"""

